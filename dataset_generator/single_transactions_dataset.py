@lru_cache(maxsize=32)
def _load_data(file_path):
    # These .pt files are generated by this project and contain full
    # HeteroData objects, so we need legacy unpickling behavior.
    try:
        data_list = torch.load(file_path, weights_only=False)
    except TypeError:
        # Backward compatibility for older PyTorch versions.
        data_list = torch.load(file_path)
    return data_list

class SingleTransactionsDataset(InMemoryDataset):
    def __init__(
            self,
            root: str,
            split: str = 'train',
            transform: Optional[Callable] = None,
            pre_transform: Optional[Callable] = None,
            pre_filter: Optional[Callable] = None,
            force_reload: bool = False,
            augment_factor: int = 0,
        ) -> None:
        assert split in ['train', 'val', 'test']
        self.augment_factor = augment_factor
        self.blockchain_mapping_repo = GraphMappingBlockchainRepository(DBSession)
        self.graph_nodes_repo = GraphNodeRepository(DBSession)
        self.graph_edges_repo = GraphEdgeRepository(DBSession)

        # Ensure "raw" and "processed" subdirectories exist
        os.makedirs(os.path.join(root, 'raw'), exist_ok=True)
        os.makedirs(os.path.join(root, 'processed'), exist_ok=True)
        super().__init__(root, transform, pre_transform, pre_filter, force_reload)

    @property
    def raw_file_names(self):
        return ['blockchain_mappings.csv', 'cross_chain_mappings.csv', 'graph_nodes.csv', 'graph_edges.csv']

    @property
    def processed_file_names(self):
        return [f for f in os.listdir(self.processed_dir) if f.endswith('.pt')] + ['data_index.csv', 'metadata.json']

    @property
    def data_index(self):
        if not getattr(self, '_data_index', None):
            self._data_index = []
            path = os.path.join(self.processed_dir, 'data_index.csv')
            with open(path, 'r') as csvfile:
                reader = csv.DictReader(csvfile)
                for row in reader:
                    self._data_index.append({
                        'graph_id': row['graph_id'],
                        'tx_hash': row['tx_hash'],
                        'file_name': row['file_name'],
                        'offset': int(row['offset']),
                        'synthetic': row.get('synthetic', 'False') == 'True',
                    })
        return self._data_index
    
    @property
    def metadata(self) -> Tuple:
        if not getattr(self, '_metadata', None):
            with open(os.path.join(self.processed_dir, 'metadata.json'), 'r') as f:
                metadata = json.load(f)
            # Convert JSON lists back to tuples
            self._metadata = metadata[0], [tuple(item) for item in metadata[1]]
        return self._metadata

    #override
    def len(self):
        return len(self.data_index)
    
    def get(self, idx) -> HeteroData:
        index_entry = self.data_index[idx]
        file_name = index_entry['file_name']
        file_path = os.path.join(self.processed_dir, file_name)
        offset = index_entry['offset']
        data_list = _load_data(file_path)
        return data_list[offset]
    
    def get_by_tx_hash(self, tx_hash) -> HeteroData:
        for idx, entry in enumerate(self.data_index):
            if entry['tx_hash'] == tx_hash:
                return self.get(idx)
        raise ValueError(f"Graph with tx_hash {tx_hash} not found in dataset.")

    def convert_datatype_to_csv(self, items, columns, output_file):
        output_path = os.path.join(self.raw_dir, output_file)
        os.makedirs(self.raw_dir, exist_ok=True)  # Ensure the raw folder exists
        with open(output_path, "w") as csvfile:
            writer = csv.writer(csvfile)
            writer.writerow(columns)  # Write header
            for item in items:
                row = []
                for col in columns:
                    value = getattr(item, col)
                    # Serialize to JSON if the value is a dict or list
                    if isinstance(value, (dict, list)):
                        value = json.dumps(value)
                    row.append(value)
                writer.writerow(row)

    def download(self):
        log_to_cli("Exporting data from database to CSV files... ")
        blockchain_tx_mappings = self.blockchain_mapping_repo.get_all_non_cctx()
        blockchain_columns = [col.name for col in GraphMappingBlockchain.__table__.columns]
        self.convert_datatype_to_csv(blockchain_tx_mappings, blockchain_columns, "blockchain_mappings.csv")

        nodes = self.graph_nodes_repo.get_all_non_cctx()
        node_columns = [col.name for col in GraphNode.__table__.columns]
        self.convert_datatype_to_csv(nodes, node_columns, "graph_nodes.csv")

        edges = self.graph_edges_repo.get_all_non_cctx()
        edge_columns = [col.name for col in GraphEdge.__table__.columns]
        self.convert_datatype_to_csv(edges, edge_columns, "graph_edges.csv")

    def process(self):
        blockchain_df = pd.read_csv(os.path.join(self.raw_dir, 'blockchain_mappings.csv'))
        nodes_df = pd.read_csv(os.path.join(self.raw_dir, 'graph_nodes.csv'))
        edges_df = pd.read_csv(os.path.join(self.raw_dir, 'graph_edges.csv'), dtype={'deposit_id': 'str'})
        
        feature_extractor = FeatureExtractor(nodes_df, edges_df)

        # Also create an index file to keep track of processed graphs
        index_path = os.path.join(self.processed_dir, 'data_index.csv')
        index_file = open(index_path, 'w')
        writer = csv.writer(index_file)
        writer.writerow(['index', 'graph_id', 'tx_hash', 'file_name', 'offset', 'synthetic'])

        # We want to save up to 50 graphs in each file, so that:
        # a) We don't have a huge file that takes a long time to load / generate, and
        # b) storing all graphs in a single file would be too memory intensive during generation.
        compressed_file_number = 0
        graph_file_name = f'graph_data_{compressed_file_number}.pt'
        offset = 0
        node_types = set()
        edge_types = set()

        # Accumulated in-memory for the augmentation pass after the main loop.
        # Trade-off: doubles peak memory for large datasets, but avoids re-reading .pt files.
        real_graphs_for_aug: list = []
        real_labels_for_aug: list = []

        # Add a progress bar to track processing progresss
        pbar = tqdm(total=blockchain_df.shape[0], desc="Processing graphs", unit="graph")
        pbar.set_description("Processing single-chain graphs dataset")

        # First process single-chain graphs
        data_list = []
        for index, row in blockchain_df.iterrows():
            blockchain_graph_id = row['graph_id']

            nodes = nodes_df[nodes_df['chain_graph_id'] == blockchain_graph_id]
            edges = edges_df[edges_df['chain_graph_id'] == blockchain_graph_id]
            label = row['label']

            # Process and save the graph data
            graph_data = self.process_heterogeneous_graph(nodes, edges, label, feature_extractor)
            graph_data.bridge = row['bridge']  # Add a custom attribute to indicate the bridge (not used in model)
            graph_data.tx_hash = row['tx_hash']  # Add a custom attribute to keep track of the transaction hash (not used in model)
            if self.pre_filter is not None and not self.pre_filter(graph_data):
                continue
            if self.pre_transform is not None:
                graph_data = self.pre_transform(graph_data)

            # Save the graph position in the index file
            data_list.append(graph_data)
            writer.writerow([index, blockchain_graph_id, row['tx_hash'], graph_file_name, offset, False])
            offset += 1

            real_graphs_for_aug.append(graph_data)
            real_labels_for_aug.append(int(graph_data.y.item()))

            # Add the new node and edge types to the sets
            node_types.update(graph_data.node_types)
            edge_types.update(graph_data.edge_types)

            # Save the graph data in batches of 50 to avoid memory issues
            if len(data_list) >= 50:
                graph_file_path = os.path.join(self.processed_dir, f'graph_data_{compressed_file_number}.pt')
                torch.save(data_list, graph_file_path)
                data_list = []
                compressed_file_number += 1
                graph_file_name = f'graph_data_{compressed_file_number}.pt'
                offset = 0

            pbar.update(1)

        # Ensure any remaining graphs are saved
        if len(data_list) > 0:
            graph_file_path = os.path.join(self.processed_dir, f'graph_data_{compressed_file_number}.pt')
            torch.save(data_list, graph_file_path)
            # Advance file number so the augmentation pass never overwrites this file.
            compressed_file_number += 1
            graph_file_name = f'graph_data_{compressed_file_number}.pt'
            offset = 0

        # --- Augmentation pass ---
        # Generate synthetic copies of anomaly graphs and append them to the dataset.
        # All augmented graphs are marked with synthetic=True in the index.
        if self.augment_factor > 0:
            from dataset_generator.augmentation import augment_anomaly_graphs
            aug_anomaly_count = sum(1 for l in real_labels_for_aug if l != 0)
            print(f"Generating {aug_anomaly_count * self.augment_factor} augmented anomaly graphs (factor={self.augment_factor})...")
            aug_graphs, aug_labels = augment_anomaly_graphs(
                real_graphs_for_aug,
                real_labels_for_aug,
                augment_factor=self.augment_factor,
            )
            aug_index = len(real_graphs_for_aug)
            aug_data_list: list = []
            for aug_graph, aug_label in zip(aug_graphs, aug_labels):
                if self.pre_filter is not None and not self.pre_filter(aug_graph):
                    continue
                if self.pre_transform is not None:
                    aug_graph = self.pre_transform(aug_graph)

                aug_data_list.append(aug_graph)
                writer.writerow([
                    aug_index,
                    aug_graph.tx_hash,   # use modified tx_hash as graph_id for synthetic graphs
                    aug_graph.tx_hash,
                    graph_file_name,
                    offset,
                    True,
                ])
                offset += 1
                aug_index += 1

                node_types.update(aug_graph.node_types)
                edge_types.update(aug_graph.edge_types)

                if len(aug_data_list) >= 50:
                    graph_file_path = os.path.join(self.processed_dir, f'graph_data_{compressed_file_number}.pt')
                    torch.save(aug_data_list, graph_file_path)
                    aug_data_list = []
                    compressed_file_number += 1
                    graph_file_name = f'graph_data_{compressed_file_number}.pt'
                    offset = 0

            if aug_data_list:
                graph_file_path = os.path.join(self.processed_dir, f'graph_data_{compressed_file_number}.pt')
                torch.save(aug_data_list, graph_file_path)

        pbar.close()
        index_file.close()

        # Create a metadata file to store the unique node and edge types found in the dataset
        with open(os.path.join(self.processed_dir, 'metadata.json'), 'w') as f:
            json.dump([list(node_types), list(edge_types)], f)

    def process_heterogeneous_graph(self, nodes: pd.DataFrame, edges: pd.DataFrame, label, feature_extractor) -> HeteroData:
        graph_data = HeteroData()
        node_id_to_local_idx_by_type = {}

        # 1. Process node features by type
        for ntype, ntype_nodes_df in nodes.groupby("node_type", sort=False):
            ntype_nodes_df = ntype_nodes_df.reset_index(drop=True)
            ntype_nodes = list(ntype_nodes_df.itertuples(index=False))
            feats = torch.tensor(
                feature_extractor.compute_node_features_type(ntype_nodes, ntype, single_chain=True),
                dtype=torch.float
            )
            graph_data[ntype].x = feats

            # Each node type has its own local index space in HeteroData.
            node_id_to_local_idx_by_type[ntype] = dict(
                zip(ntype_nodes_df["node_id"].tolist(), ntype_nodes_df.index.tolist())
            )

        # Ensure every known node type has an x tensor (even if empty) so all graphs share
        # the same schema. This is required for correct PyG batching and avoids
        # 'NodeStorage has no attribute x' errors in the model for absent node types.
        for ntype, dim in get_node_type_feature_dims(single_chain=True).items():
            if ntype not in node_id_to_local_idx_by_type:
                graph_data[ntype].x = torch.zeros((0, dim), dtype=torch.float)
                node_id_to_local_idx_by_type[ntype] = {}

        # 2. Process edges
        if not edges.empty:
            node_types = nodes[["node_id", "node_type"]].drop_duplicates(subset=["node_id"])

            edges_with_types = edges[["source_id", "target_id", "edge_type"]].merge(
                node_types.rename(columns={"node_id": "source_id", "node_type": "src_type"}),
                on="source_id",
                how="left"
            ).merge(
                node_types.rename(columns={"node_id": "target_id", "node_type": "dst_type"}),
                on="target_id",
                how="left"
            )

            # As a safety measure, remove any edges where we couldn't determine the node types
            edges_with_types = edges_with_types.dropna(subset=["src_type", "dst_type", "edge_type"]) 

            for (src_type, edge_type, dst_type), group in edges_with_types.groupby(["src_type", "edge_type", "dst_type"], sort=False):
                src_map = node_id_to_local_idx_by_type.get(src_type)
                dst_map = node_id_to_local_idx_by_type.get(dst_type)
                if src_map is None or dst_map is None:
                    continue

                src_idx = group["source_id"].map(src_map)
                dst_idx = group["target_id"].map(dst_map)
                valid = src_idx.notna() & dst_idx.notna()
                if not valid.any():
                    continue

                src_idx = src_idx[valid].to_numpy(dtype=np.int64)
                dst_idx = dst_idx[valid].to_numpy(dtype=np.int64)

                edge_index = torch.tensor(np.vstack((src_idx, dst_idx)), dtype=torch.long)

                graph_data[(src_type, edge_type, dst_type)].edge_index = edge_index

        # 3. Graph-level label
        graph_data.y = torch.tensor([0 if label == BlockchainGraphLabel.NORMAL.value else 1], dtype=torch.long)
        graph_data.y_str = label  # Keep the original string label for reference

        return graph_data